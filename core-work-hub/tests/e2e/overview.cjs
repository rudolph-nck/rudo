// Browser test: Overview dashboard and Rotation page on demo data. Run after `npm run build`.
const { chromium } = require('playwright');
const file = 'file://' + require('path').resolve(__dirname, '../../dist/index.html');
const check = (c, m) => { console.log(c ? 'ok  ' : 'FAIL', m); if (!c) process.exitCode = 1; };
(async () => {
  const b = await chromium.launch();
  const p = await b.newPage({ viewport: { width: 1600, height: 1000 } });
  const errs = []; p.on('pageerror', (e) => errs.push(e.message));
  await p.goto(file + '?demo&as=nick');
  await p.evaluate(() => Object.keys(localStorage).filter((k) => k.startsWith('cwh.demo.')).forEach((k) => localStorage.removeItem(k)));
  await p.reload(); await p.waitForSelector('.hero');
  check((await p.locator('h1').first().innerText()) === 'Overview', 'Nick (manager) lands on the Overview');
  check((await p.locator('.viz-card svg[role=img]').count()) >= 5, 'charts render');
  await p.locator('.viz-card rect[tabindex]').first().hover();
  check(await p.locator('.viz-tip').isVisible(), 'hover shows a tooltip');
  const flow = p.locator('section.viz-card', { hasText: 'Flow: opened vs closed' });
  await flow.getByRole('button', { name: 'Table' }).click();
  check((await flow.locator('table tbody tr').count()) === 12, 'flow chart has a 12-week table view');
  check((await p.locator('table.team-load tbody tr').count()) === 7, 'team load lists Nick and the six analysts');
  await p.getByRole('button', { name: 'Trey', exact: false }).filter({ hasText: 'Trey' }).first().click();
  check(/Trey/.test(await p.locator('.hero-card .l').innerText()), 'clicking a person filters the dashboard');
  const n2 = await b.newPage(); await n2.goto(file + '?demo&as=nick'); await n2.waitForSelector('h1');
  check((await n2.locator('h1').first().innerText()) === 'Overview', 'managers land on the Overview');
  check((await n2.locator('.nav-group').innerText()).toLowerCase() === 'admin' && (await n2.locator('.nav button[data-section="settings"]').count()) === 1, 'managers get an Admin group with Settings');
  await n2.getByRole('button', { name: 'Collapse menu' }).click();
  check(await n2.locator('.app.collapsed').count() === 1, 'the side menu collapses to icons');
  await n2.reload(); await n2.waitForSelector('h1');
  check(await n2.locator('.app.collapsed').count() === 1, 'and stays collapsed after a reload');
  await n2.getByRole('button', { name: 'Expand menu' }).click();
  await n2.close();
  await p.goto(file + '?demo&as=nick#/rotation'); await p.waitForSelector('.timeline-shifts');
  check(/Trey/.test(await p.locator('.big-name').innerText()), 'rotation shows who is on support');
  check(/Out for now/.test(await p.locator('.rota-order').innerText()), 'someone out of rotation is marked');
  const w = await b.newPage(); await w.goto(file + '?demo&as=wes'); await w.waitForSelector('h1');
  check(/#\/mine$/.test(w.url()) || (await w.locator('.my-work').count()) === 1, 'analysts land on My work');
  check(/Good (morning|afternoon|evening), Wes/.test(await w.locator('h1').first().innerText()), 'My work greets them by name');
  check((await w.locator('.nav button').allInnerTexts()).map((t) => t.replace(/\d+/g, '').trim()).join('|') === 'My work|Board|Team', 'the team menu is short: My work, Board, Team');
  check((await w.locator('.mw-tile').count()) === 5 && (await w.locator('.mw-row').count()) > 0, 'My work shows the summary tiles and the line-up');
  await w.getByRole('radio', { name: 'By status' }).click();
  check((await w.locator('.mw-bcol').count()) === 5, 'My work switches to a by-status view');
  await w.getByRole('radio', { name: 'By due date' }).click();
  check((await w.locator('.mw-dgroup').count()) > 0, 'and a by-due-date view');
  await w.getByRole('radio', { name: 'Line-up' }).click();
  await w.goto(file + '?demo&as=wes#/audit'); await w.waitForTimeout(300);
  check(/#\/mine$/.test(w.url()), 'analysts can’t open the Audit log (sent to My work)');
  await w.goto(file + '?demo&as=wes#/board'); await w.waitForSelector('.card');
  check((await w.locator('.lane-head').count()) === 0 && (await w.locator('.board.flat').count()) === 1, 'default board is one row of columns (no swimlane rows)');
  check((await w.locator('.card .chip.bucket-badge').count()) > 0 && /^(Project|Maintenance|Support)$/.test((await w.locator('.card .chip.bucket-badge').first().innerText()).trim()), 'cards carry a Project / Maintenance / Support badge');
  await w.getByRole('radio', { name: /Support/ }).first().click().catch(() => w.getByRole('button', { name: /Support/ }).first().click());
  await w.waitForTimeout(300);
  const badges = await w.locator('.card .chip.bucket-badge').allInnerTexts();
  check(badges.length > 0 && badges.every((t) => t.trim() === 'Support'), 'the Support filter shows only Support cards');
  // Welcome entrance (shown to people; automated browsers only with ?splash)
  const sp = await b.newPage({ viewport: { width: 1200, height: 800 } });
  await sp.goto(file + '?demo&as=nick&splash');
  await sp.waitForSelector('.splash');
  check(/Welcome/.test(await sp.locator('.splash').innerText()), 'welcome screen greets the person');
  await sp.waitForSelector('.splash', { state: 'detached', timeout: 25000 });
  check((await sp.locator('.sidebar').count()) === 1, 'welcome screen gives way to the hub once loaded');
  console.log('errors', errs);
  if (errs.length) process.exitCode = 1;
  await b.close();
})();
